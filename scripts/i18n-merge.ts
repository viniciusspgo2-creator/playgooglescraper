function deepMerge(base: Dict, patch: Dict): Dict {
  const out: Dict = { ...base };
  for (const [key, value] of Object.entries(patch)) {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      out[key] = deepMerge((base[key] as Dict) ?? {}, value as Dict);
    } else {
      out[key] = value;
    }
  }
  return out;
}

